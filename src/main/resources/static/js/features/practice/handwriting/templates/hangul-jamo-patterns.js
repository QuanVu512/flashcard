(function registerHangulJamoPatterns(global) {
    const patterns = [];

    const clone = strokes => strokes.map(stroke => stroke.map(point => [...point]));

    const transform = (strokes, x, y, width, height) => strokes.map(stroke =>
        stroke.map(([pointX, pointY]) => [
            x + ((pointX / 100) * width),
            y + ((pointY / 100) * height)
        ])
    );

    const merge = (...groups) => groups.flatMap(clone);

    const circle = (centerX = 50, centerY = 50, radiusX = 34, radiusY = 34) => {
        const points = [];
        for (let index = 0; index <= 20; index++) {
            const angle = ((Math.PI * 2) * index) / 20;
            points.push([
                centerX + (Math.cos(angle) * radiusX),
                centerY + (Math.sin(angle) * radiusY)
            ]);
        }
        return [points];
    };

    const consonants = {
        "ㄱ": [[[15, 18], [82, 18], [82, 84]]],
        "ㄴ": [[[18, 15], [18, 82], [85, 82]]],
        "ㄷ": [[[18, 18], [82, 18]], [[18, 18], [18, 82]], [[18, 82], [82, 82]]],
        "ㄹ": [[[15, 14], [85, 14], [85, 36], [20, 36], [20, 60], [85, 60], [85, 84], [15, 84]]],
        "ㅁ": [[[18, 18], [82, 18]], [[18, 18], [18, 82]], [[82, 18], [82, 82]], [[18, 82], [82, 82]]],
        "ㅂ": [[[18, 15], [18, 85]], [[82, 15], [82, 85]], [[18, 18], [82, 18]], [[18, 50], [82, 50]], [[18, 82], [82, 82]]],
        "ㅅ": [[[15, 82], [50, 18]], [[50, 18], [85, 82]]],
        "ㅇ": circle(),
        "ㅈ": [[[15, 18], [85, 18]], [[15, 84], [50, 34]], [[50, 34], [85, 84]]],
        "ㅊ": [[[30, 10], [70, 10]], [[15, 30], [85, 30]], [[15, 88], [50, 44]], [[50, 44], [85, 88]]],
        "ㅋ": [[[15, 18], [82, 18], [82, 84]], [[48, 50], [85, 50]]],
        "ㅌ": [[[18, 18], [82, 18]], [[18, 18], [18, 82]], [[18, 50], [82, 50]], [[18, 82], [82, 82]]],
        "ㅍ": [[[15, 24], [85, 24]], [[15, 76], [85, 76]], [[30, 12], [30, 88]], [[70, 12], [70, 88]]],
        "ㅎ": merge([[[25, 14], [75, 14]]], circle(50, 58, 31, 27))
    };

    const vowels = {
        "ㅏ": [[[48, 10], [48, 90]], [[48, 50], [88, 50]]],
        "ㅐ": [[[32, 10], [32, 90]], [[32, 50], [62, 50]], [[72, 10], [72, 90]]],
        "ㅑ": [[[45, 8], [45, 92]], [[45, 38], [88, 38]], [[45, 64], [88, 64]]],
        "ㅒ": [[[28, 8], [28, 92]], [[28, 38], [57, 38]], [[28, 64], [57, 64]], [[72, 8], [72, 92]]],
        "ㅓ": [[[52, 10], [52, 90]], [[12, 50], [52, 50]]],
        "ㅔ": [[[28, 10], [28, 90]], [[8, 50], [28, 50]], [[70, 10], [70, 90]]],
        "ㅕ": [[[55, 8], [55, 92]], [[12, 38], [55, 38]], [[12, 64], [55, 64]]],
        "ㅖ": [[[30, 8], [30, 92]], [[8, 38], [30, 38]], [[8, 64], [30, 64]], [[72, 8], [72, 92]]],
        "ㅗ": [[[10, 68], [90, 68]], [[50, 12], [50, 68]]],
        "ㅘ": [[[8, 72], [92, 72]], [[32, 18], [32, 72]], [[70, 12], [70, 72]], [[70, 43], [94, 43]]],
        "ㅙ": [[[8, 72], [94, 72]], [[28, 18], [28, 72]], [[62, 12], [62, 72]], [[62, 43], [78, 43]], [[88, 12], [88, 72]]],
        "ㅚ": [[[8, 72], [92, 72]], [[32, 18], [32, 72]], [[72, 12], [72, 72]]],
        "ㅛ": [[[10, 72], [90, 72]], [[36, 18], [36, 72]], [[64, 18], [64, 72]]],
        "ㅜ": [[[10, 32], [90, 32]], [[50, 32], [50, 90]]],
        "ㅝ": [[[8, 28], [92, 28]], [[32, 28], [32, 86]], [[70, 28], [70, 90]], [[44, 58], [70, 58]]],
        "ㅞ": [[[8, 28], [94, 28]], [[28, 28], [28, 86]], [[62, 28], [62, 90]], [[46, 58], [62, 58]], [[88, 28], [88, 90]]],
        "ㅟ": [[[8, 28], [92, 28]], [[32, 28], [32, 86]], [[72, 28], [72, 90]]],
        "ㅠ": [[[10, 28], [90, 28]], [[36, 28], [36, 84]], [[64, 28], [64, 84]]],
        "ㅡ": [[[8, 50], [92, 50]]],
        "ㅢ": [[[8, 70], [92, 70]], [[70, 10], [70, 92]]],
        "ㅣ": [[[50, 8], [50, 92]]]
    };

    const sideBySide = (left, right) => merge(
        transform(left, 0, 8, 46, 84),
        transform(right, 54, 8, 46, 84)
    );

    Object.entries(consonants).forEach(([label, strokes]) => {
        patterns.push({label, strokes: clone(strokes)});
    });
    Object.entries(vowels).forEach(([label, strokes]) => {
        patterns.push({label, strokes: clone(strokes)});
    });

    [
        ["ㄲ", "ㄱ", "ㄱ"], ["ㄸ", "ㄷ", "ㄷ"], ["ㅃ", "ㅂ", "ㅂ"],
        ["ㅆ", "ㅅ", "ㅅ"], ["ㅉ", "ㅈ", "ㅈ"], ["ㄳ", "ㄱ", "ㅅ"],
        ["ㄵ", "ㄴ", "ㅈ"], ["ㄶ", "ㄴ", "ㅎ"], ["ㄺ", "ㄹ", "ㄱ"],
        ["ㄻ", "ㄹ", "ㅁ"], ["ㄼ", "ㄹ", "ㅂ"], ["ㄽ", "ㄹ", "ㅅ"],
        ["ㄾ", "ㄹ", "ㅌ"], ["ㄿ", "ㄹ", "ㅍ"], ["ㅀ", "ㄹ", "ㅎ"],
        ["ㅄ", "ㅂ", "ㅅ"]
    ].forEach(([label, left, right]) => {
        patterns.push({label, strokes: sideBySide(consonants[left], consonants[right])});
    });

    global.HANGUL_JAMO_PATTERNS = patterns;
})(self);
